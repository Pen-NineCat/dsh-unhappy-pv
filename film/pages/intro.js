/**
 * film/pages/intro.js — **引子（帧 0–419）的页面内容与算术**（Phase 5 / R1）。
 *
 * 这个文件只产出**纯数据与纯函数**：没有 DOM、没有 `fs`、没有 `Date`。
 * 组装成 HTML 是 `body.js` 的事，截图是 `shot.mjs` 的事。
 *
 * ## 三拍（`design-options.md` §1 / §4.14，边界与 `engine/content.js` 的 `PRELUDE_MARKS` 一致）
 *
 * | 拍 | 帧 | 时间 | 内容 |
 * |---|---|---|---|
 * | 1 注入 | 0–143 | 6.00 s | context 注入：前言先滚过去，然后是一份**为片子写的** context 文档 |
 * | 2 思考 | 144–250 | 4.46 s | 思维链：**生成到一半的英文**（不是乱码），其中一句歌词成形 1.5 s |
 * | 3 输出 | 251–418 | 7.00 s | 一段很用力的长回复，**在第 419 帧完成** |
 * | 之后 | 419– | — | 引子结束：**画面冻结在完成态**（第一幕的画面另有其人负责） |
 *
 * ## 行网格（为什么要有它）
 *
 * 滚动区整个是**一列固定 24 px 的行**（`.stage__line`，由 `body.js` 的 CSS 定义）。
 * 这不是洁癖，是**让「滚动位置 = f(t)」可被证明**：
 *
 * - 内容高 = `24 × 已显示行数` + 一点点块内边距 → 我能在**没有浏览器**的情况下算出
 *   「本帧最多能滚到哪」，于是 `want ≤ maxScroll` 是一条**单元测试**，不是一次目测。
 * - 逐帧页面最怕的是「设了 `scrollTop` 但内容不够高 → 被浏览器夹住」，
 *   那样画面会静止而**没有任何报错**（`AGENTS.md` §8 的空白帧同款陷阱）。
 *
 * 行的排版纪律（`AGENTS.md` §7「排版自己算」的网页版）：
 * 每行**硬换行**、`white-space:pre`、行盒 `overflow:hidden` —— 超长的行会被**裁掉**而不是折行，
 * 折行会让高度从 24 变成 48，整个算术崩掉。所以 `lineBudget()` 里有一条**字符预算测试**守着它。
 *
 * ## 现在**没有**做的事（如实记账）
 *
 * - 注入是「流过去 + 追底」还是「逐字吐」——⛔ 未拍板，这里取**追底**（内容逐行出现，
 *   滚动位置跟着最新一行，等价于真实聊天窗口的 auto-follow）。理由：它同时满足 §1 的
 *   「前言先滚过去」和 §1.6 的「每帧直接设滚动位置」，且**不依赖任何布局测量**。
 * - 「糊」不在这一层：浏览器出**清晰的真排版**，模糊由后期做（§1.6）。
 * - 那段 context 文档**不是本仓库的 `AGENTS.md`**，是一份为片子写的文件（§1.8）。
 */

