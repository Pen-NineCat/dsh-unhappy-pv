/**
 * 一个块一共多少个**字符**（行长之和）。
 * @param {Block} b
 * @returns {number}
 */
export function charsInBlock(b) {
  return b.lines.reduce((s, l) => s + l.length, 0);
}

/**
 * 一个块在第 `n` 帧已经吐出了**几个字符**。
 *
 * 映射把**两端都钉死**：`n = start` 时吐出第 1 个字，`n = end` 时吐完**最后一个字**。
 * 这是 `design-options.md` §1「输出在第 419 帧完成」唯一的实现方式 ——
 * 换成 `ceil(C·(n−s+1)/T)` 那种写法会**提前若干帧**收尾，
 * 于是「完成的那一瞬正好开词」这句话就不成立了（实测过一次：提前 4 帧）。
 *
 * ⚠️ **逐字，不是逐行。** 第一版是逐行（一行一次蹦出来），那是**我自己的简化**，不是要求：
 * 当时的理由是「逐字会破坏行网格的可证明性」。**这个理由是错的** ——
 * 一行的行盒高 24px 与它显示了多少个字符**无关**（行盒是按整行占位、用 `overflow:hidden` 裁的），
 * 所以逐字完全不影响 `内容高 = 24 × 行盒数`。
 * 作者动态检查时指出了这一点（"一行一行而不是一个字一个字"），于是改成逐字。
 *
 * 公式：`1 + floor((n−s)·(C−1)/(T−1))`，夹在 `[0, C]`；反解见 `frameOfChar()`。
 * @param {Block} b
 * @param {number} n
 * @returns {number}
 */
export function charsRevealed(b, n) {
  const C = charsInBlock(b);
  if (C <= 0) return 0;
  if (n < b.start) return 0;
  if (C === 1) return 1;
  const T = b.end - b.start + 1;
  if (n >= b.end) return C;
  const grown = 1 + Math.floor(((n - b.start) * (C - 1)) / (T - 1));
  return Math.max(0, Math.min(C, grown));
}

/**
 * @typedef {Object} Reveal
 * @property {number} full 已经完全吐出来的行数
 * @property {string} partial 正在吐的那一行的**已显示前缀**（没有则空串）
 * @property {number} partialIndex 正在吐的那一行的行号（`full`，没有则 -1）
 * @property {number} boxes 这一块当前占的**行盒数**（`full + (partial ? 1 : 0)`）—— 内容高只认它
 * @property {number} chars 已吐出的字符数
 */

/**
 * 把一个块的字符进度拆成「整行 + 半行」。
 * @param {Block} b
 * @param {number} n
 * @returns {Reveal}
 */
export function revealAt(b, n) {
  const chars = charsRevealed(b, n);
  let rem = chars;
  let full = 0;
  for (const line of b.lines) {
    if (rem >= line.length) {
      rem -= line.length;
      full++;
    } else {
      // 正在吐这一行：只显示前 rem 个字符
      return {
        full,
        partial: line.slice(0, rem),
        partialIndex: full,
        boxes: full + (rem > 0 ? 1 : 0),
        chars,
      };
    }
  }
  return { full, partial: '', partialIndex: -1, boxes: full, chars };
}

/**
 * 文档在第 `n` 帧占了**几个行盒**（全文档连续计数）—— 内容高 = 它 × 24px。
 *
 * 名字保留成 `revealedLines`（历史原因），但语义是**行盒数**：正在吐的那一行也算一个盒子。
 * @param {number} n
 * @returns {number}
 */
export function revealedLines(n) {
  let sum = 0;
  for (const b of BLOCKS) sum += revealAt(b, n).boxes;
  return sum;
}

/**
 * 第 `k` 行（0 起）的**第一个字符**出现的帧号 —— `charsRevealed()` 的反解。
 *
 * `n = start + ceil(charIndex·(T−1)/(C−1))`。
 * @param {number} k
 * @returns {number}
 */
export function frameOfLineStart(k) {
  const { block, index } = locateLine(k);
  const before = block.lines.slice(0, index).reduce((s, l) => s + l.length, 0);
  return frameOfChar(block, before);
}

/**
 * 第 `k` 行（0 起）的**最后一个字符**出现的帧号。
 * `frameOfLineStart(k+1) - 1` 与它相等，但这里直接按字符算，不依赖下一行的存在。
 * @param {number} k
 * @returns {number}
 */
export function frameOfLineDone(k) {
  const { block, index } = locateLine(k);
  const before = block.lines.slice(0, index).reduce((s, l) => s + l.length, 0);
  const last = before + Math.max(0, block.lines[index].length - 1);
  return frameOfChar(block, last);
}

/**
 * 块内第 `i` 个字符（0 起）出现的帧号。
 * @param {Block} b
 * @param {number} i
 * @returns {number}
 */
export function frameOfChar(b, i) {
  const C = charsInBlock(b);
  if (C <= 1) return b.start;
  const T = b.end - b.start + 1;
  return Math.min(b.end, Math.max(b.start, b.start + Math.ceil((i * (T - 1)) / (C - 1))));
}

/** 歌词第一行（英文那句）在文档里的全局行号。 */
export function lyricLineIndex() {
  let base = 0;
  for (const b of BLOCKS) {
    if (b.key === 'thinking') return base + LYRIC_INDEX_IN_THINK;
    base += b.lines.length;
  }
  throw new Error('BLOCKS 里没有 thinking 块');
}

/**
 * 歌词「成形」的窗口（帧，闭区间）。§1 要求它**清楚 1–2 秒**。
 *
 * 起点 = 英文那句**吐完最后一个字**的那一帧（逐字之后，"成形"的自然是吐完的那一刻）；
 * 长度取 1.5 s = 36 帧。中文那行紧随其后（约 1–2 帧），落在窗口内。
 * @param {number} [seconds]
 * @returns {{from: number, to: number, frames: number}}
 */
export function lyricWindow(seconds = 1.5) {
  const from = frameOfLineDone(lyricLineIndex());
  const frames = Math.round(seconds * FPS);
  return { from, to: from + frames - 1, frames };
}

/**
 * 歌词的「清楚度」：1 = 完全成形，0 = 和别的思维链文字一样。
 *
 * 它是 `n` 的纯函数，而且**可以给后期用**：`design-options.md` §1.6 把「糊」交给后期，
 * 后期若想让歌词那 1.5 s 少糊一点，读这个数就行，不用去猜帧号。
 * @param {number} n
 * @returns {number} 0..1
 */
export function lyricEmphasis(n) {
  const { from, to } = lyricWindow();
  if (n < from || n > to) return 0;
  const fadeIn = 4;
  const fadeOut = 8;
  if (n < from + fadeIn) return (n - from + 1) / fadeIn;
  if (n > to - fadeOut) return Math.max(0, (to - n) / fadeOut);
  return 1;
}

/**
 * 第 `n` 帧的滚动窗口高（px）。
 * 它就是「舞台高 − 固定区高 − 输入框高」，三个数都是我们自己定的，所以**不需要测量**。
 * @param {number} height 舞台高（CSS px）
 * @returns {number}
 */
export function scrollWindowHeight(height) {
  const h = height - FIXED_HEIGHT - COMPOSER_HEIGHT;
  if (h < LINE_H * 4) {
    throw new Error(
      `intro: 舞台高 ${height}px 减去固定区 ${FIXED_HEIGHT}px 与输入框 ${COMPOSER_HEIGHT}px 之后` +
        `只剩 ${h}px —— 滚动区放不下 4 行。\n` +
        `  hint: 视口高要 > ${FIXED_HEIGHT + COMPOSER_HEIGHT + LINE_H * 4}px；引子的目标矩形是 960×640`,
    );
  }
  return h;
}

/**
 * 第 `n` 帧的滚动位置（px）—— **`t` 的纯函数，且不需要任何布局测量**。
 *
 * 规则：**把最新吐出来的那一行压到窗口底部**（真实聊天窗口的 auto-follow）。
 * `scrollAtFrame(n) = max(0, 内容高(n) − 窗口高)`，而 `内容高(n) = 24 × 已显示行数 + 块内边距`。
 *
 * 于是「设了 `scrollTop` 但内容不够高、被浏览器夹住」这件事在**算术上不可能发生**：
 * 这个值**恰好就是** `maxScroll`（`scrollHeight − clientHeight`）。
 * `film/test/pages.test.js` 里有一条测试对**全片 4741 帧**验证 `want ≤ maxScroll`。
 * @param {number} n 帧号
 * @param {{height?: number}} [opts] `height` = 舞台高（CSS px），默认 640
 * @returns {number} 滚动位置（CSS px）
 */
export function scrollAtFrame(n, opts = {}) {
  const height = opts.height ?? 640;
  const win = scrollWindowHeight(height);
  const content = contentHeight(n);
  return Math.max(0, content - win);
}

/**
 * 第 `n` 帧的内容总高（px）—— 只算**已经显示的行**。
 *
 * = `24 × 已显示行数` + 思维链那块（表头一格 + `thinkBody` 的 8 px 上下内边距）。
 * 这个数**必须**等于浏览器算出来的 `scrollHeight`，`--intro-scroll-check` 就是在盯这件事。
 * @param {number} n
 * @returns {number}
 */
export function contentHeight(n) {
  const revealed = revealedLines(n);
  const think = BLOCKS.find((b) => b.key === 'thinking');
  const thinkShown = think ? revealAt(think, n).boxes : 0;
  return revealed * LINE_H + (thinkShown > 0 ? THINK_HEAD_LINES * LINE_H + THINK_BODY_PAD : 0);
}

/**
 * 一行文本的「视觉宽度」，按半角字符计（中日韩算 2）。
 * 只用来做预算检查，不参与画面。
 * @param {string} s
 * @returns {number}
 */
export function visualWidth(s) {
  let w = 0;
  for (const ch of s) {
    const c = /** @type {number} */ (ch.codePointAt(0));
    w += c >= 0x1100 && (c <= 0x115f || (c >= 0x2e80 && c <= 0xa4cf) || (c >= 0xac00 && c <= 0xd7a3) || (c >= 0xf900 && c <= 0xfaff) || (c >= 0xfe30 && c <= 0xfe6f) || (c >= 0xff00 && c <= 0xff60) || (c >= 0xffe0 && c <= 0xffe6)) ? 2 : 1;
  }
  return w;
}

/**
 * 引子的自述（报告与 `--help` 用）。
 * @returns {string}
 */
export function describe() {
  const blocks = BLOCKS.map((b) => {
    const t0 = timeAt(b.start).toFixed(3);
    const t1 = timeAt(b.end + 1).toFixed(3);
    const T = b.end - b.start + 1;
    const C = charsInBlock(b);
    const rate = ((C - 1) / Math.max(1, T - 1) * FPS).toFixed(1);
    return (
      `  ${b.label.padEnd(22)} 帧 ${String(b.start).padStart(3)}–${String(b.end).padStart(3)}  ${t0}–${t1} s` +
      `  ${String(b.lines.length).padStart(2)} 行 / ${String(C).padStart(4)} 字  ${rate} 字/s`
    );
  });
  const lw = lyricWindow();
  return [
    `引子  帧 0–${MARKS.firstLyric - 1}（${FPS} fps）· 文档 ${TOTAL_LINES} 行 · **逐字**吐出 · 行高 ${LINE_H}px · 固定区 ${FIXED_HEIGHT}px`,
    ...blocks,
    `  歌词成形           帧 ${lw.from}–${lw.to}（${(lw.frames / FPS).toFixed(2)} s，从英文那句吐完算起）`,
    `  全片               帧 0–${FRAME_COUNT - 1}`,
  ].join('\n');
}
