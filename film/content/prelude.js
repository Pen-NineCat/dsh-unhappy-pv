/**
 * film/content/prelude.js — **引子的画布侧**：占位背景 + T4 的三格骨架。
 *
 * ## 为什么这里要有两层东西
 *
 * 画面规格 §2.1 说引子的画布侧是「**5 层层堆叠背景 + 后期**」，
 * 而「层长什么样」是画面规格 §1.4 的 **⛔#4（未定）** —— 所以真正的背景**不能由我发明**。
 * 于是这一版把背景交给**已经存在的管线自检画面**（`content/example.js`）占位：
 * 它自己的画面上就写着"这不是 PV 画面，是管线自检夹具"，谁看到都不会误认。
 *
 * 第二层才是 T4 的**真内容**：`panels.js` 画的右列格子。
 * 引子前半左格盖满整幅（`leftWidthAt(n) == 1920`），右列宽 0，什么都画不出来；
 * 帧 350–418 窗口收窄，右列**自然露出来** —— 这就是 §2.1 U3 的"格子线在缩小的过程中才出现"。
 *
 * ## 为什么不能只有骨架
 *
 * 只画骨架的话，引子前半的每一帧都是**纯黑**（左格那块要等网页截图贴进来）。
 * 纯黑帧会被两条实实在在的检查拦下：护栏的「无空白帧」（stddev < 1 报警）
 * 与 Phase 7 的无损编码测试（"每帧体积该在合理范围，实际 0.4 KB/帧"）。
 * 这两条拦得对 —— 它们问的正是"这一帧是不是空的"。所以占位背景不是凑数，是**把空帧填成有内容的帧**。
 */

import { drawExample } from './example.js';
import { drawPanels } from './panels.js';

/**
 * 引子的画布侧：占位背景（管线自检画面）+ 三格骨架。
 * @param {import('../engine/frame.js').FrameState} s
 */
export function drawPrelude(s) {
  // ⚠️ 顺序有意义：自检画面先进去，骨架后画 —— 右列的面板要盖在它上面。
  drawExample(s);
  drawPanels(s);
}
